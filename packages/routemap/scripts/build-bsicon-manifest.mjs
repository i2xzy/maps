#!/usr/bin/env node
/**
 * Generate `src/bsicon-manifest.data.ts` — the set of BSicon files that actually exist.
 *
 * The icon form offers a field for anything the MODEL can represent, and the model is
 * generous: `previewOptions({kind:"track"}, "curve")` happily produces `kSTR` and `kkSTR`.
 * Neither file exists. A plain track shows 23 applicable fields and, measured against
 * Commons, four of them (`curve`, `lane`, `entry`, `offset`) have no option that resolves
 * to a real file — so a quarter of the form is choices that can only produce a broken
 * image. Representable is not the same as existing, and only Commons knows the difference.
 *
 * Existence can't be asked per render — that's an API call per option per keystroke, the
 * exact trap the {{rint}} catalog exists to avoid. So it's baked, the same way, and for
 * the same reason.
 *
 * `list=allimages` with a title prefix rather than a category: `Category:BSicon` holds 13
 * files, and the icons are spread over hundreds of descriptive subcategories with no
 * single root that enumerates them. The `BSicon ` filename prefix is the actual
 * convention, and it's mechanical.
 *
 * Stores CODES, not filenames — `BSicon_STR_red.svg` becomes `STR red`, which is what
 * `iconToCode` emits and what the renderer puts back into a URL. Only `.svg`, because
 * that's the extension the renderer builds; a legacy `.png` of the same name would be a
 * file we'd never request.
 *
 * Writes DATA ONLY, as one newline-joined string: 30k quoted-and-comma'd array elements
 * cost more bytes and more parse time than one string we split once. The hand-written
 * `src/bsicon-manifest.ts` owns the lookup, so regenerating never clobbers logic.
 *
 * Usage: node scripts/build-bsicon-manifest.mjs [--out src/bsicon-manifest.data.ts]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const API = "https://commons.wikimedia.org/w/api.php";
// Wikimedia requires a descriptive User-Agent; anonymous bulk fetches get served an
// error page instead of content.
const UA = "routemap-catalog-builder/1.0 (github.com/anthropics/routemap; dev tooling)";
const PAGE = 500; // the `allimages` ceiling for an unauthenticated client
const PAUSE_MS = 600; // be polite between calls
const RETRIES = 6; // 429s are routine on a full run, not exceptional

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(params) {
  const url = `${API}?${new URLSearchParams({ format: "json", formatversion: "2", ...params })}`;
  for (let attempt = 0; attempt < RETRIES; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (res.ok) return res.json();
    // Exponential backoff — a 429 here means slow down, not stop.
    await sleep(2000 * 2 ** attempt);
  }
  throw new Error(`giving up on ${url}`);
}

/** `BSicon_STR_red.svg` -> `STR red`; anything not a BSicon SVG -> null. */
function codeOf(name) {
  const m = /^BSicon_(.+)\.svg$/.exec(name);
  return m ? m[1].replaceAll("_", " ") : null;
}

async function main() {
  const outArg = process.argv.indexOf("--out");
  const out = resolve(
    dirname(fileURLToPath(import.meta.url)),
    "..",
    outArg > 0 ? process.argv[outArg + 1] : "src/bsicon-manifest.data.ts",
  );

  const codes = new Set();
  let skipped = 0;
  let aicontinue;
  let pages = 0;
  do {
    const data = await get({
      action: "query",
      list: "allimages",
      aiprefix: "BSicon",
      ailimit: String(PAGE),
      aiprop: "",
      ...(aicontinue ? { aicontinue } : {}),
    });
    for (const file of data.query.allimages) {
      const code = codeOf(file.name);
      if (code) codes.add(code);
      else skipped++;
    }
    aicontinue = data.continue?.aicontinue;
    if (++pages % 10 === 0) console.log(`  ${pages} pages, ${codes.size} codes…`);
    if (aicontinue) await sleep(PAUSE_MS);
  } while (aicontinue);

  const sorted = [...codes].sort();
  const body = `/**
 * GENERATED by scripts/build-bsicon-manifest.mjs — do not edit.
 *
 * Every BSicon code with a file on Wikimedia Commons, newline-separated and sorted.
 * See bsicon-manifest.ts for the lookup, and the generator for why this is baked.
 */
export const BSICON_CODES = ${JSON.stringify(sorted.join("\n"))};
`;
  writeFileSync(out, body);
  console.log(
    `${sorted.length} codes from ${pages} pages (${skipped} non-SVG skipped) -> ${out}`,
  );
}

await main();
